def render_profile(primary: str, secondary: str | None = None, notes: str = "", status: str = "active") -> str:
    main = PRESETS[primary]
    support = PRESETS.get(secondary) if secondary else None
    lines = [
        "# 语言风格档案",
        "",
        "## 选择",
        "",
        f"- 状态：`{status}`",
        f"- 主风格：`{primary}`（{main['name']}）",
        f"- 辅风格：`{secondary}`（{support['name']}）" if support else "- 辅风格：无",
        "- 执行原则：主风格控制可读性和叙事底盘；辅风格只调整局部质感，发生冲突时服从主风格。",
        "",
        "## 主风格参数",
        "",
        f"- 阅读承诺：{main['promise']}",
        f"- 叙事距离：{main['perspective']}",
        f"- 句式节奏：{main['sentence']}",
        f"- 词汇质地：{main['diction']}",
        f"- 对白机制：{main['dialogue']}",
        f"- 意象密度：{main['imagery']}",
        f"- 信息交代：{main['exposition']}",
        f"- 场景速度：{main['tempo']}",
        f"- 禁用倾向：{main['avoid']}",
    ]
    if support:
        lines.extend(
            [
                "",
                "## 辅风格调节",
                "",
                f"- 阅读质感：{support['promise']}",
                f"- 可借用：{support['sentence']} {support['imagery']}",
                f"- 不得带入：{support['avoid']}",
            ]
        )
    lines.extend(
        [
            "",
            "## 作者手法转译",
            "",
            "- 参考来源：无",
            "- 借鉴手法：无",
            "- 明确排除：标志性措辞、固定句式复刻、角色或段落改写式仿作。",
            "",
            "## 个人声音证据",
            "",
            "- 状态：`provisional`",
            "- 样本：尚未提供作者亲手修改的配对样本或已确认原创样稿。",
            "- 执行：暂按主风格写作；作者确认改稿后，从真实改动更新保留倾向、删除倾向、对白差异和收尾习惯。",
            "- 边界：不把未经作者确认的 AI 初稿当作个人声音基线。",
            "",
            "## 项目定制",
            "",
            notes.strip() or "无额外约束。",
            "",
            "## 连载一致性锚点",
            "",
            "每次写章前读取本档案和最近两章。审查叙事距离、句式节奏、对白机制、意象密度与禁用倾向；只有剧情压力导致的局部变化可以偏离，偏离后应回归底盘。",
            "",
        ]
    )
    return "\n".join(lines)


def render_custom_profile(style_id: str, title: str, technique_card: str, notes: str = "") -> str:
    return f"""# 语言风格档案

## 选择

- 状态：`active`
- 主风格：`custom:{style_id}`（{title}）
- 辅风格：无
- 执行原则：只执行下列可描述手法，不复刻参考作者的标志性表达。

## 手法转译卡

{technique_card.strip()}

## 项目定制

{notes.strip() or "无额外约束。"}

## 个人声音证据

- 状态：`provisional`
- 样本：尚未提供作者亲手修改的配对样本。
- 执行：自定义手法卡控制已描述维度；作者确认改稿后再从真实差异更新个人声音规则。
- 边界：不把未经作者确认的 AI 初稿当作个人声音基线。

## 硬边界

- 不复制参考文本中的句子、比喻、人物、场景或段落结构。
- 不要求“写得像某作者”；把要求改写为叙事距离、句式、词汇、对白、意象、信息和节奏参数。
- 连载一致性优先于临时炫技；每章写前读取本档案和最近两章。
"""


